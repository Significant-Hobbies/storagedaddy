import Darwin
import Foundation

/// Recoverability guidance, never proof that a folder is unused or safe to delete.
public enum CleanupGuidance {
    /// uv owns cache locking and shared installed environments. Its supported
    /// cleaner keeps the cache root and lock; direct Trash/delete is unsafe.
    public static func requiredNativeCleaner(path: String, home: String = FileManager.default.homeDirectoryForCurrentUser.path) -> String? {
        let candidate = normalized(path)
        for relative in [".cache/uv", "Library/Caches/uv"] {
            let cache = normalized(home) + "/" + relative
            if candidate == cache || candidate.hasPrefix(cache + "/") { return "uv cache clean" }
            if cache.hasPrefix(candidate.hasSuffix("/") ? candidate : candidate + "/"), FileManager.default.fileExists(atPath: cache) { return "uv cache clean" }
        }
        return nil
    }
    public static func chromeCacheNote(path: String, home: String = FileManager.default.homeDirectoryForCurrentUser.path) -> String? {
        let cache = URL(fileURLWithPath: home).appendingPathComponent("Library/Caches/Google/Chrome").standardizedFileURL.path
        let normalized = URL(fileURLWithPath: path).standardizedFileURL.path
        guard normalized == cache || normalized.hasPrefix(cache + "/") else { return nil }
        return "This is Chrome cache, separate from your browser profile. Clearing it can remove offline site data and make pages reload; cookies and sign-ins usually remain. Quit Chrome before reviewing cleanup."
    }

    public static func label(for category: DeveloperCategory?) -> String {
        switch category {
        case .packageCaches, .nodeModules, .installedModules: "Usually regenerable"
        case .installers: "Usually re-downloadable"
        case .claudeSessions, .codexSessions: "Not regenerable · archive first"
        default: "Regeneration unconfirmed"
        }
    }

    public static func explanation(for category: DeveloperCategory?) -> String {
        switch category {
        case .packageCaches:
            "Usually downloadable again. Offline or unavailable versions and local changes may be lost."
        case .nodeModules, .installedModules:
            "Usually reinstallable from the project's dependency manifest. Check that required versions are available and no local changes need keeping."
        case .buildOutputs:
            "A build-folder name does not confirm that its contents can be rebuilt. Check the project and build inputs before cleanup."
        case .claudeSessions, .codexSessions:
            "Conversation history cannot be regenerated by reinstalling the tool. Preserve an archive before cleanup."
        case .installers:
            "An installer is not the installed app. If the app is installed and still distributed, the installer can usually be downloaded again — verify before cleanup."
        case .oldDownloads:
            "Age alone does not make a file safe to remove. Some downloads are the only copy of a file; review contents before cleanup."
        default:
            "May contain original work or persistent data. Regeneration has not been confirmed; review contents before cleanup."
        }
    }

    /// Batch suggestions deliberately exclude broad stores, local repositories,
    /// environments and name-only build matches. Existing preflight still applies.
    public static func isSuggestedCache(category: DeveloperCategory, path: String, home: String = FileManager.default.homeDirectoryForCurrentUser.path) -> Bool {
        if category == .modelCaches {
            return normalized(path) == normalized(home) + "/.cache/huggingface/hub"
        }
        guard category == .packageCaches else { return false }
        let url = URL(fileURLWithPath: path)
        let parent = url.deletingLastPathComponent().standardizedFileURL.path
        let base = URL(fileURLWithPath: home).standardizedFileURL
        let roots = [base.appendingPathComponent("Library/Caches").path, base.appendingPathComponent(".cache").path]
        let aliases = roots.map { "/System/Volumes/Data" + $0 }
        let tool = url.lastPathComponent.lowercased()
        return (roots + aliases).contains(parent)
            && ["npm", "pnpm", "yarn", "pip", "uv", "homebrew", "go-build", "cocoapods", "composer", "ccache", "sccache"].contains(tool)
    }

    /// Installed runtimes are not project dependencies or disposable build outputs.
    public static func isInstalledRuntime(path: String) -> Bool {
        let path = normalized(path)
        let parts = path.lowercased().split(separator: "/").map(String.init)
        return parts.contains { $0.hasSuffix(".app") || $0.hasSuffix(".framework") || $0.hasSuffix(".xpc") }
            || path.hasPrefix("/usr/") || path.hasPrefix("/opt/") || path.hasPrefix("/System/")
            || path.hasPrefix("/Library/")
            || path.hasSuffix("/lib/node_modules")
            || path.contains("/node-tools/") || path.contains("/node-runtime/")
            || path.contains("/corepack/v1/")
            || ["/.vscode/extensions/", "/.cursor/extensions/", "/.devin/extensions/", "/.lmstudio/extensions/",
                "/.volta/tools/image/", "/.nvm/versions/node/", "/.bun/install/global/", "/.config/opencode/"].contains(where: path.contains)
    }

    /// Project dependencies move as one folder; package contents need no audit.
    public static func isProjectDependencies(path: String) -> Bool {
        URL(fileURLWithPath: path).lastPathComponent == "node_modules"
            && isRegenerableFolder(path: path)
    }

    /// Only Node dependency trees and bounded download caches may bypass Trash.
    /// Installed runtimes, manifests and other data keep their recovery path.
    public static func canDeletePermanently(path: String, home: String = FileManager.default.homeDirectoryForCurrentUser.path) -> Bool {
        guard !isInstalledRuntime(path: path) else { return false }
        if isProjectDependencies(path: path) { return true }
        let normalizedPath = normalized(path)
        if normalizedPath == normalized(home) + "/.npm/_cacache" { return true }
        return ["npm", "pnpm", "yarn"].contains(URL(fileURLWithPath: path).lastPathComponent.lowercased())
            && isSuggestedCache(category: .packageCaches, path: path, home: home)
    }

    /// These folders can change normally between scan and review. Project
    /// dependencies use folder-level checks; other candidates retain deeper checks.
    public static func isRegenerableFolder(path: String, home: String = FileManager.default.homeDirectoryForCurrentUser.path) -> Bool {
        guard !isInstalledRuntime(path: path) else { return false }
        if normalized(path) == normalized(home) + "/.npm/_cacache"
            || isSuggestedCache(category: .packageCaches, path: path, home: home)
            || isSuggestedCache(category: .modelCaches, path: path, home: home) { return true }
        let url = URL(fileURLWithPath: path).standardizedFileURL
        let name = url.lastPathComponent
        let normalizedPath = normalized(path)
        let normalizedHome = normalized(home)
        if name == "__pycache__" { return true }
        if name == "DerivedData", normalizedPath.hasPrefix(normalizedHome + "/Library/Developer/") { return true }
        let manifests: [String]
        switch name {
        case "node_modules", ".next", ".nuxt": manifests = ["package.json"]
        case ".build": manifests = ["Package.swift"]
        case "target": manifests = ["Cargo.toml"]
        case "build", "dist": manifests = ["package.json", "Package.swift", "Cargo.toml", "CMakeLists.txt", "pyproject.toml"]
        default: return false
        }
        return manifests.contains { name in
            var info = stat()
            let manifest = url.deletingLastPathComponent().appendingPathComponent(name)
            return lstat(manifest.path, &info) == 0 && info.st_mode & S_IFMT == S_IFREG
        }
    }

    static func normalized(_ path: String) -> String {
        let value = URL(fileURLWithPath: path).standardizedFileURL.path
        return value.hasPrefix("/System/Volumes/Data/") ? String(value.dropFirst("/System/Volumes/Data".count)) : value
    }

    public static func quickCleanupIDs(in scan: ScanResult, findings: [DeveloperFinding], home: String = FileManager.default.homeDirectoryForCurrentUser.path) -> [Int] {
        let eligible = findings.filter { [.packageCaches, .modelCaches, .nodeModules, .buildOutputs].contains($0.category) }
        let possible = eligible.flatMap { finding -> [Int] in
            guard scan.nodes.indices.contains(finding.id) else { return [] }
            // Keep Hugging Face's tokens outside the downloadable hub cache.
            let hub = finding.category == .modelCaches ? scan.nodes[finding.id].children.filter {
                scan.nodes.indices.contains($0) && scan.nodes[$0].name == "hub"
            } : []
            return [finding.id] + hub
        }
        let candidates = Set(possible.filter {
            scan.nodes[$0].parent != nil && scan.nodes[$0].isDirectory
                && requiredNativeCleaner(path: scan.url(for: $0).path, home: home) == nil
                && isRegenerableFolder(path: scan.url(for: $0).path, home: home)
        })
        return candidates.filter { id in
            var parent = scan.nodes[id].parent
            while let next = parent, scan.nodes.indices.contains(next) {
                if candidates.contains(next) { return false }
                parent = scan.nodes[next].parent
            }
            return true
        }.sorted { scan.nodes[$0].allocatedBytes > scan.nodes[$1].allocatedBytes }
    }
}
